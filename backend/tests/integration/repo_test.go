package integration_test

import (
	"context"
	"errors"
	"os"
	"testing"
	"time"

	"ksp/internal/repository"
	"ksp/internal/repository/models"
	pgrepo "ksp/internal/repository/postgres"

	pgdriver "gorm.io/driver/postgres"
	"gorm.io/gorm"
	"gorm.io/gorm/logger"
)

func openTestDB(t *testing.T) *gorm.DB {
	t.Helper()

	dsn := os.Getenv("TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("TEST_DATABASE_URL is not set")
	}

	db, err := gorm.Open(pgdriver.Open(dsn), &gorm.Config{
		Logger: logger.Default.LogMode(logger.Silent),
	})
	if err != nil {
		t.Fatalf("open db: %v", err)
	}

	sqlDB, err := db.DB()
	if err != nil {
		t.Fatalf("sql db: %v", err)
	}
	sqlDB.SetConnMaxLifetime(time.Minute)

	if err := db.Exec(`
		CREATE TABLE IF NOT EXISTS threats (
			id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			md5 VARCHAR(32) NOT NULL UNIQUE,
			name TEXT NOT NULL,
			severity VARCHAR(255) NOT NULL DEFAULT 'medium',
			description TEXT,
			category VARCHAR(255) NOT NULL DEFAULT 'other',
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
		)
	`).Error; err != nil {
		t.Fatalf("prepare table: %v", err)
	}

	t.Cleanup(func() {
		_ = db.Exec("DELETE FROM threats WHERE md5 LIKE 'test%'").Error
		_ = sqlDB.Close()
	})

	return db
}

func TestPostgresRepo_CRUD(t *testing.T) {
	db := openTestDB(t)
	repo := pgrepo.NewRepo(db)
	ctx := context.Background()
	md5 := "test" + "aaaaaaaaaaaaaaaaaaaaaaaaaaaa"

	_ = db.Where("md5 = ?", md5).Delete(&models.Threat{})

	err := repo.Create(ctx, &models.Threat{
		MD5:      md5,
		Name:     "integration-threat",
		Severity: "medium",
		Category: "test",
	})
	if err != nil {
		t.Fatalf("create: %v", err)
	}

	got, err := repo.GetByMD5(ctx, md5)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if got.Name != "integration-threat" {
		t.Fatalf("unexpected name: %s", got.Name)
	}
	if got.CreatedAt.IsZero() || got.UpdatedAt.IsZero() {
		t.Fatalf("timestamps must be set: %+v", got)
	}

	err = repo.Create(ctx, &models.Threat{MD5: md5, Name: "dup", Severity: "low", Category: "other"})
	if !errors.Is(err, repository.ErrConflict) {
		t.Fatalf("want conflict, got %v", err)
	}

	err = repo.Update(ctx, md5, &models.Threat{
		Name:     "updated",
		Severity: "high",
		Category: "test",
	})
	if err != nil {
		t.Fatalf("update: %v", err)
	}

	got, err = repo.GetByMD5(ctx, md5)
	if err != nil {
		t.Fatalf("get after update: %v", err)
	}
	if got.Name != "updated" || got.Severity != "high" {
		t.Fatalf("unexpected updated threat: %+v", got)
	}

	err = repo.Update(ctx, "testbbbbbbbbbbbbbbbbbbbbbbbbbbbb", &models.Threat{Name: "x", Severity: "low", Category: "other"})
	if !errors.Is(err, repository.ErrNotFound) {
		t.Fatalf("want not found, got %v", err)
	}
}

func TestPostgresRepo_RespectsTimeout(t *testing.T) {
	db := openTestDB(t)
	repo := pgrepo.NewRepo(db)

	ctx, cancel := context.WithTimeout(context.Background(), 0)
	defer cancel()

	_, err := repo.GetByMD5(ctx, "testcccccccccccccccccccccccccccc")
	if !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("want deadline exceeded, got %v", err)
	}
}
